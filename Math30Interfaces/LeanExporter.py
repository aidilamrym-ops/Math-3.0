import os
import re
import sys
from fractions import Fraction

TOOLS_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tools")
if TOOLS_DIR not in sys.path:
    sys.path.insert(0, TOOLS_DIR)

from smt_lean_bridge import compile_lean, find_placeholders  # noqa: E402

# Kept for callers that still want the rational rendering.  New certificates use
# exact integer cross-multiplication so they compile without Mathlib.
def _format_to_lean_rational(value_str: str) -> str:
    frac = Fraction(value_str)
    return f"({frac.numerator} : ℚ) / {frac.denominator}"


def _cross_multiplied_inequality(const_val: str, bound_val: str) -> str | None:
    """Return a Lean integer inequality equivalent to const_val <= bound_val.

    Both denominators are positive by construction of ``Fraction``.  The
    inequality ``a/b <= c/d`` is equivalent to ``a*d <= c*b``.  ``None`` means
    the requested bound is false on its face, so no certificate may be emitted.
    """
    left = Fraction(str(const_val))
    right = Fraction(str(bound_val))
    if left > right:
        return None
    left_scaled = left.numerator * right.denominator
    right_scaled = right.numerator * left.denominator
    return f"({left_scaled} : Int) ≤ ({right_scaled} : Int)"


class LeanFormalExporter:
    def __init__(self, workspace_root: str):
        self.root = os.path.abspath(workspace_root)
        if not os.path.isfile(os.path.join(self.root, "manifest.json")):
            sys.exit(1)

    def format_to_lean_rational(self, value_str: str) -> str:
        return _format_to_lean_rational(value_str)

    def export_bounds_theorem(
        self,
        output_filename: str,
        theorem_name: str,
        constants: dict,
        bounds: dict,
    ) -> bool:
        target_path = os.path.join(self.root, "Math30Interfaces", output_filename)
        clauses: list[str] = []
        for key, bound_val in bounds.items():
            const_val = constants.get(key, key)
            clause = _cross_multiplied_inequality(str(const_val), str(bound_val))
            if clause is None:
                # Fail closed: never emit a theorem whose arithmetic is false.
                return False
            clauses.append(clause)

        body = " ∧\n    ".join(clauses) if clauses else "True"
        lean_lines = [
            "/- Generated by Math30Interfaces/LeanExporter.py.",
            "   Exact integer cross-multiplication; no Mathlib import is required. -/",
            "",
            f"theorem {theorem_name} :",
            f"    {body} := by",
            "  decide",
            "",
        ]
        try:
            os.makedirs(os.path.dirname(target_path), exist_ok=True)
            with open(target_path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write("\n".join(lean_lines))
        except OSError:
            return False

        compilation = compile_lean(target_path, cwd=self.root, timeout=180)
        if not compilation["compiled"]:
            return False
        with open(target_path, "r", encoding="utf-8") as handle:
            return not find_placeholders(handle.read())
