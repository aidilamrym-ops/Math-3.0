#!/usr/bin/env python3
"""Typed claims ledger: distinguish Lean claims from code references.

The previous implementation treated every backticked token in README.MD as a
"tracked claim".  That counted shell commands, directory names, tool names and
trust-token vocabulary as claims and produced an inflated headline count.

This version assigns an explicit type to every citation:

  * ``lean-claim``       — a Lean-ish identifier (snake_case or dotted name).
                           It is a claim only if the theorem-name audit resolves
                           it to a declaration; otherwise it is ``unresolved``
                           and the tool exits 1.
  * ``file-reference``   — a path or a token ending in a code suffix.
  * ``tooling``          — flags, commands, build terms and trust-token names.
  * ``prose-term``       — any other backticked term (not a theorem claim).

Only ``lean-claim`` rows count toward the README's "Tracked Claims" headline.
Every row records its provenance and whether it actually resolves.

Outputs:
  reports/claims/ledger.json
  reports/claims/ledger.md
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.MD"
REPORTS = ROOT / "reports"
LEDGER_DIR = REPORTS / "claims"
THEOREM_AUDIT_JSON = REPORTS / "readme_theorem_audit.json"

MATHLIB_INDICATORS = {"mathlib"}
BOUNDED_KEYWORDS = {"finite", "lattice", "bounded", "model", "evidence"}
NUMERICAL_KEYWORDS = {
    "zeta", "riemann", "hypothesis", "critical", "interval", "trace", "spectral"
}
CODE_SUFFIXES = (
    ".lean", ".py", ".json", ".md", ".txt", ".smt2", ".toml",
    ".sh", ".yml", ".yaml", ".html", ".svg", ".tex",
)
LEANISH = re.compile(r"[A-Za-z_][A-Za-z0-9_'.]*")
# Trust-token vocabulary, CLI flags and build terms are not theorem claims.
TOOLING = {
    "sorry", "sorryax", "admit", "axiom", "constant", "opaque", "partial",
    "native_decide", "implemented_by", "extern", "true", "false", "exit",
    "manifest", "json", "lean", "mathlib", "python", "lake", "z3", "unsat",
    "sat", "sha", "gpl", "cc", "orcid", "doi", "github", "make", "gate",
    "tools", "rfl", "omega", "linarith", "nlinarith", "norm_num", "decide",
    "interval_cases", "simp", "aesop", "positivity", "ring", "apply", "rw",
    "exact", "constructor", "induction", "cases", "unfold", "pycache",
    "__pycache__", "reports", "smt", "staging", "exports", "mcp",
    "lean_spec", "workflow",
}
NEGATIVE_MARKERS = (
    "do not exist", "does not exist", "not exist in the module",
    "no longer exists", "was removed", "were removed", "is false",
    "are false", "is refuted", "are refuted", "not proved", "not proven",
)
AUTO_FACTS_RE = re.compile(
    r"<!-- AUTO-FACTS:START -->.*?<!-- AUTO-FACTS:END -->", re.DOTALL
)


def semantic_readme_digest(text: str) -> str:
    """Digest of authored README prose, excluding generated provenance.

    Both the auto-facts block and the manifest seal digest are generated by
    other tools; including either would make a fresh receipt stale immediately
    after injection or reseal.
    """
    semantic = AUTO_FACTS_RE.sub("", text)
    semantic = re.sub(r"(?<![0-9a-f])[0-9a-f]{64}(?![0-9a-f])", "<sha256>", semantic)
    return hashlib.sha256(semantic.encode("utf-8")).hexdigest()


def negative_tail(line: str, end: int, span: int = 180) -> bool:
    """Negation that follows the cited token in the same clause."""
    tail = line[end:end + span].lower()
    for separator in (". ", "; ", " — "):
        index = tail.find(separator)
        if index != -1:
            tail = tail[:index]
    return any(marker in tail for marker in NEGATIVE_MARKERS)


def extract_cited(readme_text: str) -> list[tuple[str, str, bool]]:
    """Return (identifier, prose line, negative_mention), order-preserving."""
    entries: list[tuple[str, str, bool]] = []
    for line in readme_text.splitlines():
        for match in re.finditer(r"`([^`\n]+)`", line):
            ident = match.group(1).strip()
            if ident:
                entries.append(
                    (ident, line.strip(), negative_tail(line, match.end()))
                )
    seen: set[str] = set()
    deduped: list[tuple[str, str, bool]] = []
    for ident, prose, negative in entries:
        if ident not in seen:
            seen.add(ident)
            deduped.append((ident, prose, negative))
    return deduped


def classify(ident: str, prose: str, resolved_map: dict, negative: bool) -> dict:
    lowered = ident.lower()
    artifacts = resolved_map.get(ident, [])

    if (
        "/" in ident
        or "\\" in ident
        or lowered.endswith(CODE_SUFFIXES)
    ):
        kind = "file-reference"
    elif lowered.lstrip("-").startswith("-") or lowered in TOOLING:
        kind = "tooling"
    elif (
        negative
        and LEANISH.fullmatch(ident)
        and ("_" in ident or "." in ident)
    ):
        kind = "negative-reference"
    elif LEANISH.fullmatch(ident) and ("_" in ident or "." in ident):
        kind = "lean-claim"
    else:
        kind = "prose-term"

    if kind == "lean-claim":
        status = "resolved" if artifacts else "unresolved"
        provenance = detect_provenance(artifacts[0]) if artifacts else "unknown"
        claim_class = detect_class(ident, prose) if artifacts else "unresolved"
    else:
        status = "not-a-declaration"
        provenance = "n/a"
        claim_class = kind

    return {
        "id": ident,
        "prose": prose,
        "artifact": artifacts,
        "theorem_name": ident,
        "kind": kind,
        "status": status,
        "is_claim": kind == "lean-claim",
        "provenance": provenance,
        "class": claim_class,
    }


def detect_provenance(path: str) -> str:
    lowered = path.lower()
    if any(indicator in lowered for indicator in MATHLIB_INDICATORS):
        return "imported"
    return "local"


def detect_class(name: str, prose: str) -> str:
    lowered_name = name.lower()
    lowered_prose = prose.lower()
    if any(keyword in lowered_prose for keyword in NUMERICAL_KEYWORDS):
        return "numerical evidence"
    if any(
        keyword in lowered_name or keyword in lowered_prose
        for keyword in BOUNDED_KEYWORDS
    ):
        return "bounded model"
    if "cantor_no_surjection" in lowered_name or "finitary_information" in lowered_name:
        return "kernel theorem"
    return "kernel theorem"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--readme", default=None)
    parser.add_argument("--out-dir", default=None)
    args = parser.parse_args()

    readme_path = Path(args.readme).resolve() if args.readme else README
    readme_text = readme_path.read_text(encoding="utf-8")
    out_dir = Path(args.out_dir).resolve() if args.out_dir else LEDGER_DIR
    out_dir.mkdir(parents=True, exist_ok=True)

    audit_path = THEOREM_AUDIT_JSON
    if audit_path.is_file():
        audit = json.loads(audit_path.read_text(encoding="utf-8"))
    else:
        print(
            f"WARNING: {audit_path} not found — run readme_theorem_audit.py first.",
            file=sys.stderr,
        )
        audit = {}
    resolved_map = audit.get("resolved_map", {})

    ledger = [
        classify(ident, prose, resolved_map, negative)
        for ident, prose, negative in extract_cited(readme_text)
    ]
    claims = [entry for entry in ledger if entry["is_claim"]]
    unresolved = [entry["id"] for entry in claims if entry["status"] == "unresolved"]

    payload = {
        "generated": datetime.now(timezone.utc).isoformat(),
        "readme": str(readme_path.relative_to(ROOT)) if readme_path.is_relative_to(ROOT) else str(readme_path),
        "readme_semantic_sha256": semantic_readme_digest(readme_text),
        "entries": len(ledger),
        "claims": len(claims),
        "resolved_claims": len(claims) - len(unresolved),
        "unresolved_claims": unresolved,
        "ledger": ledger,
    }
    (out_dir / "ledger.json").write_text(
        json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8"
    )

    by_kind: dict[str, int] = {}
    for entry in ledger:
        by_kind[entry["kind"]] = by_kind.get(entry["kind"], 0) + 1

    md = [
        "# Claims Ledger",
        "",
        f"- Generated: {payload['generated']}",
        f"- README: `{payload['readme']}`",
        f"- Total backticked citations: **{len(ledger)}**",
        f"- Lean claims: **{len(claims)}** "
        f"(resolved: {payload['resolved_claims']}, unresolved: {len(unresolved)})",
        f"- Citation kinds: `{by_kind}`",
        "",
        "## Lean claims",
        "",
        "| ID | Status | Artifact(s) | Provenance | Class |",
        "|---|---|---|---|---|",
    ]
    for entry in claims:
        artifacts = ", ".join(entry["artifact"]) or "—"
        md.append(
            f"| `{entry['id']}` | {entry['status']} | `{artifacts}` | "
            f"`{entry['provenance']}` | `{entry['class']}` |"
        )
    md += ["", "## Non-declaration citations", ""]
    md += [
        f"- `{entry['id']}` — {entry['kind']}"
        for entry in ledger
        if not entry["is_claim"]
    ]
    (out_dir / "ledger.md").write_text("\n".join(md) + "\n", encoding="utf-8")

    print(
        f"ledger entries={len(ledger)} claims={len(claims)} "
        f"unresolved={len(unresolved)}"
    )
    for ident in unresolved:
        print(f"UNRESOLVED: {ident}")
    return 0 if not unresolved else 1


if __name__ == "__main__":
    sys.exit(main())
