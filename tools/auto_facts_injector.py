#!/usr/bin/env python3
"""Auto-facts injector for README.MD — fail-closed evidence summary.

The block between ``<!-- AUTO-FACTS:START -->`` and ``<!-- AUTO-FACTS:END -->``
is generated exclusively from executable evidence:

  * ``manifest.json``                       — pinned-file ledger
  * ``reports/full_surface_lean_audit.json`` — canonical compile receipt
  * ``reports/claims/ledger.json``          — tracked claim ledger
  * ``reports/readme_theorem_audit.json``   — theorem-name resolution receipt

No fact is ever filled from a hard-coded default.  A missing, stale, partial or
failed receipt is rendered as ``NOT CERTIFIED`` and makes the process exit 1;
it is never rounded up to a PASS.  This closes the defect that let a one-file
``--only`` audit receipt produce the line
``Full-Surface Lean Files: 1 (100% compiled PASS)``.

Freshness is checked against source mtimes, not against a self-declared flag:
a receipt generated before the newest audited ``.lean`` file is stale by
definition.  The same rule applies to the theorem and claim receipts with
respect to ``README.MD``.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.MD"
REPORTS = ROOT / "reports"
MANIFEST = ROOT / "manifest.json"
FULL_AUDIT = REPORTS / "full_surface_lean_audit.json"
THEOREM_AUDIT = REPORTS / "readme_theorem_audit.json"
CLAIM_LEDGER = REPORTS / "claims" / "ledger.json"

LEAN_SURFACES = (
    ROOT / "lean" / "spec_v4",
    ROOT / "Math30Kernel",
    ROOT / "Math30Interfaces",
)
EXCLUDED_PARTS = {".git", "__pycache__", ".lake", "staging", "fixtures", "repaired"}
AUTO_FACTS_RE = re.compile(
    r"<!-- AUTO-FACTS:START -->.*?<!-- AUTO-FACTS:END -->", re.DOTALL
)


def semantic_readme_digest(text: str) -> str:
    """Digest of authored README prose, excluding generated provenance.

    The auto-facts block and every 64-hex seal anchor are generated by other
    tools, so they are excluded from the freshness comparison.
    """
    semantic = AUTO_FACTS_RE.sub("", text)
    semantic = re.sub(r"(?<![0-9a-f])[0-9a-f]{64}(?![0-9a-f])", "<sha256>", semantic)
    return hashlib.sha256(semantic.encode("utf-8")).hexdigest()


def enumerate_lean() -> list[Path]:
    files: list[Path] = []
    for surface in LEAN_SURFACES:
        if not surface.is_dir():
            continue
        for current, dirnames, filenames in os.walk(surface):
            dirnames[:] = [d for d in dirnames if d not in EXCLUDED_PARTS]
            files.extend(
                Path(current) / name for name in filenames if name.endswith(".lean")
            )
    return sorted(set(files))


def load_json(path: Path) -> object | None:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def parse_local_timestamp(value: object) -> float | None:
    """Parse the audit's local-time ``%Y-%m-%d %H:%M:%S`` stamp."""
    if not isinstance(value, str):
        return None
    try:
        return datetime.strptime(value, "%Y-%m-%d %H:%M:%S").timestamp()
    except ValueError:
        return None


def parse_iso_timestamp(value: object) -> float | None:
    if not isinstance(value, str):
        return None
    try:
        return datetime.fromisoformat(value.replace("Z", "+00:00")).timestamp()
    except ValueError:
        return None


def main() -> int:
    problems: list[str] = []
    readme_text = README.read_text(encoding="utf-8") if README.is_file() else ""
    readme_mtime = README.stat().st_mtime if README.is_file() else 0.0
    semantic_digest = semantic_readme_digest(readme_text)

    # ---- manifest ---------------------------------------------------------
    manifest = load_json(MANIFEST) if MANIFEST.is_file() else None
    if isinstance(manifest, dict) and manifest:
        manifest_rows = f"{len(manifest):,}"
    else:
        manifest_rows = "UNREADABLE"
        problems.append("manifest.json missing or not a JSON object")

    # ---- Lean surface -----------------------------------------------------
    lean_files = enumerate_lean()
    actual_lean = len(lean_files)
    audit = load_json(FULL_AUDIT) if FULL_AUDIT.is_file() else None
    audit_ok = False
    audit_detail = "no canonical full-surface receipt"
    if isinstance(audit, dict):
        total = audit.get("total_files")
        compiled = audit.get("compiled")
        counts = audit.get("counts") or {}
        failures = audit.get("failures") or []
        complete = audit.get("is_complete") is True
        # Legacy receipts predate the explicit is_complete marker.  They are
        # accepted only when their own counts prove completeness.
        legacy_complete = (
            total == actual_lean
            and compiled == total
            and counts == {"PASS": total}
            and not failures
        )
        generated = parse_local_timestamp(audit.get("generated"))
        newest_source = max((p.stat().st_mtime for p in lean_files), default=0.0)
        fresh = generated is not None and generated + 2.0 >= newest_source
        if total != actual_lean:
            problems.append(
                f"Lean receipt covers {total} files but {actual_lean} exist"
            )
        if not (complete or legacy_complete):
            problems.append("Lean receipt is not a complete all-PASS run")
        if not fresh:
            problems.append("Lean receipt predates the newest Lean source")
        if compiled != total or failures:
            problems.append(
                f"Lean receipt compiled {compiled}/{total} with {len(failures)} failures"
            )
        if complete or (legacy_complete and fresh and total == actual_lean):
            audit_ok = True
            audit_detail = (
                f"{actual_lean} files, all compiled PASS "
                f"(receipt {audit.get('generated', 'unknown')})"
            )
        else:
            audit_detail = (
                f"{actual_lean} files enumerated; NOT CERTIFIED "
                f"(receipt {total if total is not None else 'missing'} files, "
                f"complete={str(complete).lower()}, fresh={str(fresh).lower()})"
            )
    else:
        problems.append("canonical full-surface Lean receipt unreadable")

    # ---- theorem-name audit ----------------------------------------------
    theorem = load_json(THEOREM_AUDIT) if THEOREM_AUDIT.is_file() else None
    if isinstance(theorem, dict):
        cited = theorem.get("cited_identifiers")
        resolved = theorem.get("resolved")
        missing = theorem.get("missing", [])
        theorem_time = parse_iso_timestamp(theorem.get("generated")) or THEOREM_AUDIT.stat().st_mtime
        recorded_digest = theorem.get("readme_semantic_sha256")
        if isinstance(recorded_digest, str):
            theorem_fresh = recorded_digest == semantic_digest
        else:
            # Legacy receipt: no semantic digest, fall back to mtime.
            theorem_fresh = theorem_time + 2.0 >= readme_mtime
        theorem_ok = (
            isinstance(cited, int)
            and isinstance(resolved, int)
            and cited > 0
            and resolved == cited
            and not missing
            and theorem_fresh
        )
        theorem_text = f"{resolved}/{cited} {'PASS' if theorem_ok else 'FAIL'}"
        if not theorem_ok:
            problems.append(
                "theorem-name receipt is stale or has unresolved identifiers"
            )
    else:
        theorem_text = "NOT CERTIFIED"
        problems.append("theorem-name receipt unreadable")

    # ---- claim ledger -----------------------------------------------------
    claims = load_json(CLAIM_LEDGER) if CLAIM_LEDGER.is_file() else None
    if isinstance(claims, dict) and isinstance(claims.get("ledger"), list):
        claim_rows = claims["ledger"]
        claim_count = claims.get("claims")
        unresolved_claims = claims.get("unresolved_claims") or []
        if not isinstance(claim_count, int):
            claim_count = sum(1 for row in claim_rows if row.get("is_claim"))
        claims_count = f"{claim_count:,} Lean claims"
        recorded_digest = claims.get("readme_semantic_sha256")
        if isinstance(recorded_digest, str):
            ledger_fresh = recorded_digest == semantic_digest
        else:
            ledger_fresh = CLAIM_LEDGER.stat().st_mtime + 2.0 >= readme_mtime
        if not ledger_fresh:
            claims_count += " (STALE)"
            problems.append("claim ledger predates README.MD")
        if unresolved_claims:
            claims_count += f" ({len(unresolved_claims)} unresolved)"
            problems.append(
                f"claim ledger has {len(unresolved_claims)} unresolved Lean claim(s)"
            )
    elif isinstance(claims, list):
        # Legacy untyped ledger: countable but not certifiable.
        claims_count = f"{len(claims):,} (UNTYPED)"
        problems.append("claim ledger is the legacy untyped format")
    else:
        claims_count = "UNREADABLE"
        problems.append("claim ledger missing or empty")

    # ---- inline README claims that must not drift -------------------------
    # When (and only when) the full-surface receipt is complete and fresh, the
    # numeric Lean-surface claims are rewritten from the enumerated file count.
    # A failed audit never silently "fixes" the prose to match itself.
    if audit_ok:
        readme_text = re.sub(
            r"\b\d+-file Lean surface\b",
            f"{actual_lean}-file Lean surface",
            readme_text,
        )
        readme_text = re.sub(
            r"\b\d+ Lean files under\b",
            f"{actual_lean} Lean files under",
            readme_text,
        )
        readme_text = re.sub(
            r"\b\d+/\d+ PASS, 0 FAIL",
            f"{actual_lean}/{actual_lean} PASS, 0 FAIL",
            readme_text,
        )

    for match in re.finditer(r"\b(\d+)-file Lean surface\b", readme_text):
        claimed = int(match.group(1))
        if claimed != actual_lean:
            problems.append(
                f"README states a {claimed}-file Lean surface; {actual_lean} exist"
            )

    # ---- render and inject ------------------------------------------------
    snippet = (
        "<!-- AUTO-FACTS:START -->\n"
        f"- **Manifest Pinned Files:** {manifest_rows}\n"
        f"- **Lean Surface:** {audit_detail}\n"
        f"- **Tracked Claims in Ledger:** {claims_count}\n"
        f"- **Resolved README Theorem Names:** {theorem_text}\n"
        f"- **Evidence Status:** {'PASS' if not problems else 'FAIL — ' + '; '.join(problems)}\n"
        "<!-- AUTO-FACTS:END -->"
    )

    if not README.is_file():
        print("README.MD not found.")
        return 1

    pattern = re.compile(r"<!-- AUTO-FACTS:START -->.*?<!-- AUTO-FACTS:END -->", re.DOTALL)
    if pattern.search(readme_text):
        new_text = pattern.sub(snippet, readme_text)
    else:
        new_text = readme_text + "\n\n## Auto-Facts Summary\n\n" + snippet + "\n"

    if new_text != readme_text:
        README.write_text(new_text, encoding="utf-8")
        print("README.MD updated with evidence-derived auto-facts.")
    else:
        print("README.MD auto-facts already current.")

    for problem in problems:
        print(f"EVIDENCE FAIL: {problem}")
    return 0 if not problems and audit_ok else 1


if __name__ == "__main__":
    sys.exit(main())
